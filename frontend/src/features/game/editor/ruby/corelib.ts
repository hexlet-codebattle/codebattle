// The part of Ruby's core library battle solutions use, written for ./analysis.
//
// An entry is `name(params) {block} → Return — doc`; `(params)` and `{block}` are optional.
// Types: Integer, Float, String, Symbol, Boolean, nil, Array[E], Hash[K, V], Set[E],
// Range[E], Tuple[A, B] (a pair like a hash entry), `?` for unknown. In an entry, E/K/V are
// the receiver's type arguments, `self` the receiver, `$0`… the type of that argument.
// `{E, Integer}` lists what the block yields: `each_with_index { |e, i| }`; a yielded Tuple
// is splatted over several block parameters, as Ruby does (`hash.each { |k, v| }`).

export interface RubyClass {
  params: string[];
  members: string[];
  /** What `x[i]` gives. */
  index?: string;
  doc: string;
}

